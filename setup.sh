#!/usr/bin/env bash
# Install Java, vsearch, cutadapt, and Nextflow for the SUNi library count.
# Writes env.sh in the repository root.
#
#   ./setup.sh
#   source env.sh
#
# Python 3.9 or later must already be installed.

set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
PREFIX="$ROOT/.tools"
BIN="$PREFIX/bin"
VENV="$PREFIX/venv"
JDK="$PREFIX/jdk"

JAVA_VERSION=21.0.13
JAVA_BUILD=9
VSEARCH_VERSION=2.32.0
CUTADAPT_VERSION=5.2
NEXTFLOW_VERSION=25.10.4

die() {
    printf 'setup.sh: %s\n' "$*" >&2
    exit 1
}

jdk_arch() {
    local os arch
    os=$(uname -s)
    arch=$(uname -m)
    case "$os:$arch" in
        Darwin:arm64) printf 'aarch64_mac\n' ;;
        Darwin:x86_64) printf 'x64_mac\n' ;;
        Linux:x86_64) printf 'x64_linux\n' ;;
        Linux:aarch64 | Linux:arm64) printf 'aarch64_linux\n' ;;
        *) die "no JDK build for $os $arch" ;;
    esac
}

vsearch_asset() {
    local os arch
    os=$(uname -s)
    arch=$(uname -m)
    case "$os:$arch" in
        Darwin:arm64) printf 'macos-aarch64\n' ;;
        Darwin:x86_64) printf 'macos-x86_64\n' ;;
        Linux:x86_64) printf 'linux-x86_64\n' ;;
        Linux:aarch64 | Linux:arm64) printf 'linux-aarch64\n' ;;
        *) die "no vsearch build for $os $arch" ;;
    esac
}

clear_quarantine() {
    if [[ "$(uname -s)" == Darwin ]]; then
        xattr -dr com.apple.quarantine "$1" 2>/dev/null || true
    fi
}

command -v python3 >/dev/null 2>&1 || die "python3 was not found"
python3 -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 9) else 1)' \
    || die "python3 >= 3.9 is required"

mkdir -p "$BIN"

java_text=""
if [[ -x "$JDK/bin/java" ]]; then
    java_text=$("$JDK/bin/java" -version 2>&1 || true)
fi
if [[ "$java_text" == *"\"${JAVA_VERSION}"* ]]; then
    printf 'Java %s is already installed\n' "$JAVA_VERSION"
else
    jdk_platform=$(jdk_arch)
    asset="OpenJDK21U-jdk_${jdk_platform}_hotspot_${JAVA_VERSION}_${JAVA_BUILD}.tar.gz"
    url="https://github.com/adoptium/temurin21-binaries/releases/download/jdk-${JAVA_VERSION}%2B${JAVA_BUILD}/${asset}"
    stage=$(mktemp -d)
    trap 'rm -rf "$stage"' EXIT
    printf 'downloading %s\n' "$asset"
    curl -fL --retry 3 -o "$stage/$asset" "$url"
    tar -xzf "$stage/$asset" -C "$stage"
    java_bin=$(find "$stage" -path '*/bin/java' \( -type f -o -type l \) -print -quit)
    [[ -n "$java_bin" ]] || die "JDK archive has no bin/java"
    java_home=$(CDPATH= cd -- "$(dirname "$java_bin")/.." && pwd)
    rm -rf "$JDK"
    mv "$java_home" "$JDK"
    rm -rf "$stage"
    trap - EXIT
    clear_quarantine "$JDK"
fi

plat=$(vsearch_asset)
vsearch_text=""
if [[ -x "$BIN/vsearch" ]]; then
    vsearch_text=$("$BIN/vsearch" --version 2>&1 || true)
fi
if [[ "$vsearch_text" == *"v${VSEARCH_VERSION}"* ]]; then
    printf 'vsearch %s is already installed\n' "$VSEARCH_VERSION"
else
    asset="vsearch-${VSEARCH_VERSION}-${plat}.tar.gz"
    url="https://github.com/torognes/vsearch/releases/download/v${VSEARCH_VERSION}/${asset}"
    stage=$(mktemp -d)
    trap 'rm -rf "$stage"' EXIT
    printf 'downloading %s\n' "$asset"
    curl -fL --retry 3 -o "$stage/$asset" "$url"
    tar -xzf "$stage/$asset" -C "$stage"
    cp "$stage/vsearch-${VSEARCH_VERSION}-${plat}/bin/vsearch" "$BIN/vsearch"
    chmod +x "$BIN/vsearch"
    clear_quarantine "$BIN/vsearch"
    rm -rf "$stage"
    trap - EXIT
fi

if [[ ! -x "$VENV/bin/python" ]]; then
    rm -rf "$VENV"
    python3 -m venv --copies "$VENV"
fi
cutadapt_version=""
if [[ -x "$VENV/bin/cutadapt" ]]; then
    cutadapt_version=$("$VENV/bin/cutadapt" --version 2>/dev/null || true)
fi
if [[ "$cutadapt_version" == "$CUTADAPT_VERSION" ]]; then
    printf 'cutadapt %s is already installed\n' "$CUTADAPT_VERSION"
else
    printf 'installing cutadapt %s\n' "$CUTADAPT_VERSION"
    "$VENV/bin/python" -m pip install --disable-pip-version-check "cutadapt==${CUTADAPT_VERSION}"
fi

nextflow_version=""
if [[ -f "$BIN/nextflow" ]]; then
    nextflow_version=$(sed -n "s/^NXF_VER=\${NXF_VER:-'\([^']*\)'}/\1/p" "$BIN/nextflow")
fi
if [[ "$nextflow_version" == "$NEXTFLOW_VERSION" ]]; then
    printf 'nextflow %s is already installed\n' "$NEXTFLOW_VERSION"
else
    printf 'downloading nextflow %s\n' "$NEXTFLOW_VERSION"
    curl -fL --retry 3 -o "$BIN/nextflow" \
        "https://github.com/nextflow-io/nextflow/releases/download/v${NEXTFLOW_VERSION}/nextflow-${NEXTFLOW_VERSION}-dist"
    chmod +x "$BIN/nextflow"
    clear_quarantine "$BIN/nextflow"
fi

cat > "$ROOT/env.sh" <<EOF
# Generated by setup.sh. Source this file before running the workflow.
export JAVA_HOME="$JDK"
export PATH="\$JAVA_HOME/bin:$VENV/bin:$BIN:\$PATH"
EOF

java_text=$("$JDK/bin/java" -version 2>&1 || true)
printf 'java: %s\n' "${java_text%%$'\n'*}"
vsearch_text=$("$BIN/vsearch" --version 2>&1 || true)
printf 'vsearch: %s\n' "${vsearch_text%%$'\n'*}"
printf 'cutadapt: %s\n' "$("$VENV/bin/cutadapt" --version)"
nextflow_version=$(sed -n "s/^NXF_VER=\${NXF_VER:-'\([^']*\)'}/\1/p" "$BIN/nextflow")
printf 'nextflow: %s\n' "$nextflow_version"
printf 'source %s\n' "$ROOT/env.sh"
